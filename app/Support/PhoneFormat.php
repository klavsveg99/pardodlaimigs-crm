    public static function display(string|int|float|null $value): ?string
    {
        $value = trim((string) $value);

        if ($value === '') {
            return $value;
        }

        $compact = preg_replace('/[\s().\/-]+/', '', $value) ?? $value;

        if (! str_starts_with($compact, '+')) {
            return $value;
        }

        $digits = substr($compact, 1);

        foreach (self::DIAL_CODES as $code) {
            if (strlen($code) < strlen($digits) && str_starts_with($digits, $code)) {
                return '+'.$code.' '.substr($digits, strlen($code));
            }
        }

        // Nav atpazīts prefikss — atstājam tā, kā ir.
        return '+'.$digits;
    }
}
